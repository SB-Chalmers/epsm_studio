from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    source = ROOT / "tokens.json"
    data = json.loads(source.read_text())
    tokens = data["tokens"]
    declarations = "\n".join(f"  --epsm-{key}: {value};" for key, value in tokens.items())
    css = f"/* Generated from tokens.json · Pocket CAD {data['version']}. Do not edit. */\n.epsm-pocket-cad {{\n{declarations}\n}}\n"

    def resolve(value):
        if isinstance(value, dict):
            return {k: resolve(v) for k, v in value.items()}
        if isinstance(value, list):
            return [resolve(v) for v in value]
        if isinstance(value, str) and re.fullmatch(r"\{[^}]+\}", value):
            return tokens[value[1:-1]]
        return value

    maps = {"schema_version": 1, "version": data["version"], **resolve(data["maps"])}
    manifest = {
        "schema_version": 1,
        "version": data["version"],
        "source": "tokens.json",
        "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "exports": {"tokens.css": hashlib.sha256(css.encode()).hexdigest()},
    }
    map_json = json.dumps(maps, indent=2, ensure_ascii=False) + "\n"
    manifest["exports"]["maps.json"] = hashlib.sha256(map_json.encode()).hexdigest()
    icons = json.loads((ROOT / "icons" / "manifest.json").read_text())
    preview_data = {"version": data["version"], "tokens": tokens,
                    "artwork_palette": data["artwork_palette"],
                    "icons": [{"id": i["id"], "label": i["label"], "role": i["role"]} for i in icons["icons"]]}
    preview_js = "// Generated by scripts/build_tokens.py.\nwindow.EPSM_POCKET_CAD = " + json.dumps(preview_data, ensure_ascii=False) + ";\n"
    manifest["exports"]["preview-data.js"] = hashlib.sha256(preview_js.encode()).hexdigest()
    return {"tokens.css": css, "maps.json": map_json, "preview-data.js": preview_js,
            "tokens.manifest.json": json.dumps(manifest, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report missing or stale exports without writing.")
    args = parser.parse_args()
    stale = []
    for name, content in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_bytes() != content.encode():
                stale.append(name)
        else:
            path.write_text(content)
    if stale:
        parser.exit(1, "Stale token exports: " + ", ".join(stale) + "\n")
    print("Pocket CAD tokens: " + ("4 exports current" if args.check else "4 exports generated"))


if __name__ == "__main__":
    main()
