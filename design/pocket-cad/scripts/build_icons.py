def validate(source: dict) -> None:
    if source.get("version") != "1.0.0" or source.get("grid_size") != 32:
        raise ValueError("Expected version 1.0.0 and a 32-pixel source grid")
    expected = {"I":"#252B2B", "C":"#F1E9D6", "T":"#B5B2A8", "S":"#777D78", "R":"#E9543F"}
    if source.get("palette") != expected:
        raise ValueError("The pack must use the agreed five-colour palette")
    if tuple(entry["id"] for entry in source["icons"]) != IDS:
        raise ValueError("Missing, duplicate or incorrectly ordered repository IDs")
    for entry in source["icons"]:
        grid = entry["grid"]
        if len(grid) != 32 or any(len(row) != 32 for row in grid):
            raise ValueError(f'{entry["id"]}: grid must be exactly 32×32')
        used = set("".join(grid))
        if not used <= set(expected) | {"."} or not {"I", "C", "R"} <= used:
            raise ValueError(f'{entry["id"]}: invalid palette or missing ink/cream/active red')
        coordinates = [(x,y) for y,row in enumerate(grid) for x,p in enumerate(row) if p != "."]
        if any(not 2 <= x <= 29 or not 2 <= y <= 29 for x,y in coordinates):
            raise ValueError(f'{entry["id"]}: preserve two pixels of keyline padding')
        dark = dark_grid(grid)
        if any(dark[y][x] != grid[y][x] for x,y in coordinates):
            raise ValueError(f'{entry["id"]}: keyline changed original artwork')
    # This is a meaningful topology guard: a capacitor branches from the red
    # junction to ground. Its dielectric gap may not become a direct wire.
    rc = next(entry["grid"] for entry in source["icons"] if entry["id"] == "epsm_rc")
    if rc[10][21] != "R" or rc[18][21] != "I" or rc[21][21] != "I":
        raise ValueError("RC junction or capacitor plates have moved; review topology checks")
    if rc[19][21] != "." or rc[20][21] != ".":
        raise ValueError("RC capacitor dielectric gap must remain open")
    if rc[10][28] != "C" or rc[10][24] != "I":
        raise ValueError("RC output must remain connected to the junction")


def build(source: dict) -> dict[str, bytes]:
    validate(source)
    palette, entries = source["palette"], source["icons"]
    files: dict[str, bytes] = {}
    manifest = {
        "name": "EPSM Pocket CAD", "version": source["version"], "grid_size": 32,
        "license": "MIT", "attribution": "EPSM contributors",
        "source": "source.json", "source_file_sha256": sha256((ROOT / "source.json").read_bytes()),
        "palette": palette, "png_sizes": list(SIZES),
        "dark_variant": "One cream pixel around the silhouette; original pixel colours preserved.",
        "hash_algorithm": "sha256", "path_base": "icons/", "icons": [],
    }
    for entry in entries:
        ident, original = entry["id"], entry["grid"]
        dark = dark_grid(original)
        paths_by_format = {"svg": f"svg/{ident}.svg", "dark_svg": f"svg/dark/{ident}.svg", "png": {}, "dark_png": {}}
        files[paths_by_format["svg"]] = svg(entry, original, palette)
        files[paths_by_format["dark_svg"]] = svg(entry, dark, palette, True)
        for size in SIZES:
            for variant, grid in (("", original), ("dark/", dark)):
                path = f"png/{variant}{size}/{ident}.png"
                paths_by_format["dark_png" if variant else "png"][str(size)] = path
                files[path] = png(expanded(grid, palette, size))
        owned_paths = [paths_by_format["svg"], paths_by_format["dark_svg"], *paths_by_format["png"].values(), *paths_by_format["dark_png"].values()]
        source_bytes = json.dumps({"palette": palette, "icon": entry}, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()
        manifest["icons"].append({
            "id": ident, "label": entry["label"], "role": entry["role"],
            "sourcehash": sha256(source_bytes), "files": paths_by_format,
            "filehashes": {path: sha256(files[path]) for path in owned_paths},
        })
    symbols = []
    for entry in entries:
        for suffix, grid in (("", entry["grid"]), ("-dark", dark_grid(entry["grid"]))):
            ident = entry["id"] + suffix
            symbols.append(f'<symbol id="{ident}" viewBox="0 0 32 32"><title>{html.escape(entry["label"])}</title>\n{paths(grid,palette)}\n</symbol>')
    files["sprite.svg"] = ('<svg xmlns="http://www.w3.org/2000/svg" shape-rendering="crispEdges">\n<!-- SPDX-License-Identifier: MIT; EPSM contributors -->\n' + "\n".join(symbols) + "\n</svg>\n").encode()
    files["catalogue.html"] = catalogue(entries)
    files["contact-sheet.png"] = contact_sheet(entries, palette, False)
    files["contact-sheet-dark.png"] = contact_sheet(entries, palette, True)
    manifest["packfiles"] = {path: sha256(files[path]) for path in ("sprite.svg", "catalogue.html", "contact-sheet.png", "contact-sheet-dark.png")}
    files["manifest.json"] = json_bytes(manifest)
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare expected exports byte-for-byte without writing")
    args = parser.parse_args()
    try:
        source = json.loads((ROOT / "source.json").read_text())
        files = build(source)
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"Icon source error: {error}", file=sys.stderr)
        return 1
    failures = []
    for name, content in files.items():
        path = ROOT / name
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                failures.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    expected_exports = {name for name in files if name.endswith((".svg", ".png"))}
    actual_exports = {str(path.relative_to(ROOT)) for folder in (ROOT / "svg", ROOT / "png") if folder.exists() for path in folder.rglob("*") if path.is_file()}
    extras = actual_exports - expected_exports
    if extras:
        failures.extend(f"unexpected export: {name}" for name in sorted(extras))
    if failures:
        print("Icon exports differ:\n" + "\n".join(failures), file=sys.stderr)
        return 1
    verb = "Verified" if args.check else "Built"
    print(f"{verb} {len(IDS)} native icons, {len(IDS)*2} SVGs, {len(IDS)*len(SIZES)*2} PNGs and catalogue; {len(files)} deterministic outputs.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
