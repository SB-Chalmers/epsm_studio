def json_bytes(value: object) -> bytes:
    return (json.dumps(value, indent=2, ensure_ascii=False) + "\n").encode()


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def rgba(hex_value: str) -> tuple[int, int, int, int]:
    return tuple(int(hex_value[i:i+2], 16) for i in (1, 3, 5)) + (255,)


def png(pixels: list[list[tuple[int, int, int, int]]]) -> bytes:
    height, width = len(pixels), len(pixels[0])
    raw = b"".join(b"\0" + bytes(v for pixel in row for v in pixel) for row in pixels)

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xffffffff)

    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(raw, 9))
        + chunk(b"IEND", b"")
    )


def expanded(grid: list[str], palette: dict[str, str], size: int) -> list[list[tuple[int, int, int, int]]]:
    factor = size // 32
    colours = {key: rgba(value) for key, value in palette.items()}
    colours["."] = TRANSPARENT
    return [[colours[grid[y // factor][x // factor]] for x in range(size)] for y in range(size)]


def dark_grid(grid: list[str]) -> list[str]:
    """One cream pixel around the original silhouette, with original pixels intact."""
    result = [list(row) for row in grid]
    for y, row in enumerate(grid):
        for x, colour in enumerate(row):
            if colour == ".":
                continue
            for dy in (-1, 0, 1):
                for dx in (-1, 0, 1):
                    nx, ny = x + dx, y + dy
                    if 0 <= nx < 32 and 0 <= ny < 32 and grid[ny][nx] == ".":
                        result[ny][nx] = "C"
    return ["".join(row) for row in result]


def paths(grid: list[str], palette: dict[str, str]) -> str:
    output = []
    for key, colour in palette.items():
        runs = []
        for y, row in enumerate(grid):
            x = 0
            while x < 32:
                if row[x] != key:
                    x += 1
                    continue
                start = x
                while x < 32 and row[x] == key:
                    x += 1
                runs.append(f"M{start} {y}h{x-start}v1H{start}z")
        if runs:
            output.append(f'<path fill="{colour}" d="{"".join(runs)}"/>')
    return "\n".join(output)


def svg(entry: dict, grid: list[str], palette: dict[str, str], dark: bool = False) -> bytes:
    title = html.escape(entry["label"] + (" — dark background" if dark else ""))
    description = html.escape(entry["role"])
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32" viewBox="0 0 32 32" '
        'role="img" aria-labelledby="title description" shape-rendering="crispEdges">\n'
        '<!-- SPDX-License-Identifier: MIT; Copyright (c) 2026 EPSM contributors -->\n'
        f'<title id="title">{title}</title>\n<desc id="description">{description}</desc>\n'
        + paths(grid, palette) + "\n</svg>\n"
    ).encode()


def put(canvas: list, x: int, y: int, colour: tuple, scale: int = 1) -> None:
    for yy in range(y, y + scale):
        for xx in range(x, x + scale):
            if 0 <= yy < len(canvas) and 0 <= xx < len(canvas[0]):
                canvas[yy][xx] = colour


def text(canvas: list, value: str, x: int, y: int, colour: tuple, scale: int = 1) -> None:
    for char in value.upper():
        for row, bits in enumerate(FONT.get(char, FONT[" "])):
            for column in range(5):
                if bits & (1 << (4 - column)):
                    put(canvas, x + column*scale, y + row*scale, colour, scale)
        x += 6*scale


def contact_sheet(entries: list[dict], palette: dict[str, str], dark: bool) -> bytes:
    width, height = 1056, 832
    bg = rgba("#252B2B" if dark else "#FCFBF8")
    fg = rgba("#F1E9D6" if dark else "#252B2B")
    muted = rgba("#B5B2A8" if dark else "#777D78")
    canvas = [[bg for _ in range(width)] for _ in range(height)]
    text(canvas, "EPSM / POCKET CAD", 32, 28, fg, 3)
    text(canvas, "32 PX NATIVE / FIVE COLOURS / MIT / 1.0.0", 32, 62, muted, 2)
    for index, entry in enumerate(entries):
        column, row = index % 4, index // 4
        x, y = 32 + column*256, 102 + row*226
        grid = dark_grid(entry["grid"]) if dark else entry["grid"]
        enlarged = expanded(grid, palette, 128)
        for yy, line in enumerate(enlarged):
            for xx, colour in enumerate(line):
                if colour[3]:
                    canvas[y+yy][x+44+xx] = colour
        native = expanded(grid, palette, 32)
        for yy, line in enumerate(native):
            for xx, colour in enumerate(line):
                if colour[3]:
                    canvas[y+143+yy][x+92+xx] = colour
        # Long repository IDs use 1x lettering instead of changing icon scale.
        scale = 1 if len(entry["id"]) > 17 else 2
        length = len(entry["id"])*6*scale - scale
        text(canvas, entry["id"], x + (216-length)//2, y+190, fg, scale)
    text(canvas, "EDITABLE PIXEL GRIDS - NO CROPPED OR TRACED REFERENCE ART", 32, 802, muted, 2)
    return png(canvas)


